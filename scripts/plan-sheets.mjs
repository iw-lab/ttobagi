//    처음엔 2학년 16자·3학년 22자로 걸었는데, 배포본의 실제 최대는 20자·27자였다.
//    그 결과 멀쩡한 문항 349개가 「길이」로 탈락했다(2026-09-09). 기준이 틀리면
//    좋은 문항이 나쁜 문항으로 보인다 — 새 데이터를 옛 데이터로 재는 게 먼저다.
//    재현: node -e 로 curriculum.ts 문항 길이의 학년별 최대를 뽑는다.
const LEN = { 1: [5, 15], 2: [7, 20], 3: [12, 26], 4: [15, 28], 5: [16, 31], 6: [16, 31] };
const WORD_LEN = [2, 6];
// 겹받침은 「닭·값·흙·몫·넋·삯·삶」처럼 한 글자가 대표 낱말이다. 2자를 최소로 걸면
// 배우려는 그 낱말들이 통째로 빠진다(내장 급수표 g1-2-04 가 실제로 이 낱말들이다).
const WORD_LEN_BY_POINT = { 겹받침: [1, 6] };

const SEMESTERS = [];
for (let g = 1; g <= 6; g++) for (const s of [1, 2]) if (!(g === 1 && s === 1)) SEMESTERS.push([g, s]);

const sheets = [];
for (const [g, s] of SEMESTERS) {
  const focus = FOCUS[g];
  for (let level = 11; level <= 50; level++) {
    const k = level - 11;
    const [point, base, kind = SENT] = focus[k % focus.length];
    const topic = TOPIC[(k * 3 + g + s) % TOPIC.length];
    const [minLen, maxLen] = kind === WORD ? (WORD_LEN_BY_POINT[point] ?? WORD_LEN) : LEN[g];
    sheets.push({
      id: `g${g}-${s}-${String(level).padStart(2, '0')}`,
      grade: g, semester: s, level,
      point,
      title: `${topic} · ${base}`,
      kind, minLen, maxLen,
      topic, base,
    });
  }
}
writeFileSync('/tmp/gen5x/sheets.json', JSON.stringify(sheets, null, 1));

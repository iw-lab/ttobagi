import { describe, expect, it } from 'vitest';
import { grade } from '../src/engine/grade';

// 표준 발음법 갈래별 «전형 오류» — 아이가 들린 대로 썼을 때 무엇으로 잡히는지 본다
const CASES: [string, string, string][] = [
  ['같이', '가치', '구개음화'],
  ['굳이', '구지', '구개음화'],
  ['해돋이', '해도지', '구개음화'],
  ['맏이', '마지', '구개음화'],
  ['밭이', '바치', '구개음화'],
  ['붙이다', '부치다', '구개음화'],
  ['꽃이', '꼬치', '연음'],
  ['밥이', '바비', '연음'],
  ['옷을', '오슬', '연음'],
  ['닭이', '달기', '연음'],
  ['값이', '갑시', '연음'],
  ['앉아', '안자', '연음'],
  ['국물', '궁물', '비음화'],
  ['밥물', '밤물', '비음화'],
  ['닫는다', '단는다', '비음화'],
  ['신라', '실라', '유음화'],
  ['천리', '철리', '유음화'],
  ['난로', '날로', '유음화'],
  ['학교', '학꾜', '된소리'],
  ['봄바람', '봄빠람', '된소리'],
  ['앉았다', '안잤다', '겹받침'],
  ['없다', '업다', '겹받침'],
  ['읽다', '익다', '겹받침'],
  ['좋다', '조타', '거센소리'],
  ['많다', '만타', '거센소리'],
  ['되었다', '됬다', '준말'],
  ['안 돼', '안 되', '준말'],
  ['배게', '베개', '모음혼동'],
  ['학교에 갔다', '학교에갔다', '띄어쓰기'],
  ['가자.', '가자', '문장부호'],
  // 2026-09-14 교차검증(codex·Gemini 두 계열)에서 나온 미탐·오탐 — 전부 실측으로 재현한 뒤 고쳤다
  ['굳히다', '구치다', '구개음화'],   // ㅎ 과 만나 줄어드는 구개음화
  ['닫히다', '다치다', '구개음화'],
  ['핥이다', '할치다', '구개음화'],   // 겹받침 ㄾ 에서 넘어가는 소리는 ㅌ 이다
  ['칼날', '칼랄', '유음화'],         // 순행 유음화 — 앞 받침 ㄹ 이 뒤 ㄴ 을 ㄹ 로 만든다
  ['종로', '종노', '비음화'],         // ㄹ 의 비음화
];

/** 아직 못 잡는 것 — 숨기지 않고 적어 둔다. 고치려면 형태소 경계를 알아야 한다. */
const KNOWN_LIMITS: [string, string, string][] = [
  ['읽는다', '잉는다', '겹받침이 먼저 잡혀 비음화까지는 못 붙인다'],
  ['밭일', '바칠', 'ㄴ 첨가([반닐])를 구개음화로 본다 — 형태소 경계가 필요하다'],
];

/**
 * 표준 발음법 갈래마다 «아이가 들린 대로 쓴» 전형을 넣고, 엔진이 그 이름으로 부르는지 본다.
 * 🔴 이 배터리는 2026-09-14 에 실제로 결함 둘을 잡았다 —
 *    ① 되었다→됬다 가 「준말」이 아니라 「받침·글자빠짐」으로 나왔다
 *    ② 연음·구개음화마다 「자음혼동」이 따라붙어 설명이 둘로 갈렸다
 *    갈래를 늘릴 때는 이 표에 한 줄 더하는 것으로 족하다.
 */
describe('표준 발음법 갈래', () => {
  for (const [exp, got, want] of CASES) {
    it(`${exp} → ${got} 는 ${want}`, () => {
      expect(grade(exp, got).tags).toContain(want);
    });
  }

  it('연음·구개음화가 설명한 자리에는 «자음혼동»을 덧붙이지 않는다', () => {
    for (const [exp, got] of CASES.filter(([, , w]) => w === '연음' || w === '구개음화')) {
      expect(grade(exp, got).tags, `${exp} → ${got}`).not.toContain('자음혼동');
    }
  });

  it('유음화는 ㄴ→ㄹ 한 방향만이다 — 설날→선날 은 유음화가 아니다', () => {
    expect(grade('설날', '선날').tags).not.toContain('유음화');
    expect(grade('달님', '단님').tags).not.toContain('유음화');
  });

  it('왠·웬 은 준말이 아니다', () => {
    expect(grade('웬일', '왠일').tags).not.toContain('준말');
    expect(grade('왠지', '웬지').tags).not.toContain('준말');
  });

  it('연음과 무관한 첫소리 실수는 지우지 않는다 — 밥이→나비', () => {
    const r = grade('밥이', '나비');
    expect(r.tags).toContain('연음');
    expect(r.tags).toContain('자음혼동');
  });

  it('아직 못 잡는 것은 못 잡는다고 둔다(숨기지 않는다)', () => {
    for (const [e, a] of KNOWN_LIMITS) expect(grade(e, a).verdict).not.toBe('correct');
  });

  it('다른 자리의 받침 실수는 연음이 있어도 살아남는다', () => {
    // 「꽃이 핀다」를 「꼬치 핀다」로: 연음은 앞에서, 받침 실수는 뒤에서 따로 났다
    const r = grade('꽃이 밥을', '꼬치 바블');
    expect(r.tags).toContain('연음');
  });
});
